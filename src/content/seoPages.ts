/** Small eager index of the long-tail pages (cards, hub groups, related links). */
export const GUIDE_INDEX = guideIndex as GuideIndexEntry[]
export const GUIDE_INDEX_MAP = Object.fromEntries(GUIDE_INDEX.map((g) => [g.slug, g])) as Record<
  string,
  GuideIndexEntry
>

/**
 * Long-tail page bodies are code-split: one JSON chunk per page, loaded on demand
 * so 55 pages of copy do not ship with every route.
 */
const LAZY_PAGES = import.meta.glob<SeoPage>('./pages/*.json', { import: 'default' })
const lazyKey = (slug: string) => `./pages/${slug}.json`
const loaded: Record<string, SeoPage> = {}

export function hasLazyPage(slug: string): boolean {
  return lazyKey(slug) in LAZY_PAGES
}

/** Resolve once the page body is in memory (no-op for core pages or unknown slugs). */
export async function loadSeoPage(slug: string): Promise<void> {
  if (loaded[slug] || !hasLazyPage(slug)) return
  loaded[slug] = await LAZY_PAGES[lazyKey(slug)]()
}

/** Prerender: load every long-tail page. */
export async function loadAllSeoPages(): Promise<SeoPage[]> {
  await Promise.all(Object.keys(LAZY_PAGES).map((k) => loadSeoPage(k.slice('./pages/'.length, -'.json'.length))))
  return Object.values(loaded)
}

export const SEO_PAGES = rawPages as SeoPage[]

export const PUBLISHED_PAGES = SEO_PAGES.filter((p) => p.publish)
export const PUBLISHED_SLUGS = PUBLISHED_PAGES.map((p) => p.slug)

export const SEO_PAGE_MAP = Object.fromEntries(SEO_PAGES.map((p) => [p.slug, p])) as Record<
  string,
  SeoPage
>

export function getSeoPage(slug: string): SeoPage | undefined {
  const page = SEO_PAGE_MAP[slug] ?? loaded[slug]
  if (!page || !page.publish) return undefined
  return page
}
